export const getSeasonEngagements = (year: number, language: 'en' | 'fr'): ScheduledEngagement[] => {
  if (year === 2026) {
    const timeFormat = new Intl.DateTimeFormat(language === 'fr' ? 'fr-CA' : 'en-CA', {
      hour: 'numeric', minute: '2-digit', timeZone: ENGAGEMENT_TIME_ZONE,
    });
    return validationEngagements.map(event => ({
      id: `${event.date}-${event.area}`,
      date: event.date,
      time: `${timeFormat.format(getEngagementDate(event.date, event.start))} - ${timeFormat.format(getEngagementDate(event.date, event.end))}`,
      title: language === 'fr' ? 'Validation communautaire' : 'Community validation',
      description: language === 'fr' ? 'Validation communautaire' : 'Community validation',
      location: event.location,
      mapUrl: `https://www.google.com/maps/search/?${new URLSearchParams({ api: '1', query: `${event.location}, ${event.city}, BC` })}`,
      area: event.area,
    }));
  }
  if (year !== 2025) return [];

  const monthNumbers: Record<string, string> = { June: '06', July: '07', August: '08' };
  return engagementScheduleContent.en.engagementEvents.flatMap((month, monthIndex) => (
    month.events.flatMap((day, dayIndex) => day.sessions.map((session, sessionIndex) => {
      const localized = engagementScheduleContent[language].engagementEvents[monthIndex].events[dayIndex].sessions[sessionIndex];
      return {
        id: `2025-${monthNumbers[month.month]}-${day.date}-${sessionIndex}`,
        date: `2025-${monthNumbers[month.month]}-${day.date}`,
        time: localized.time,
        title: localized.title,
        description: localized.description,
        location: localized.location,
        mapUrl: session.mapUrl,
        area: /Bonsor|Cameron|Edmonds|Taylor|Central|Confederation|Bob Prittie|Fraser|BNH/.test(session.location)
          ? 'burnaby' as const : 'comoxValley' as const,
      };
    }))
  ));
};


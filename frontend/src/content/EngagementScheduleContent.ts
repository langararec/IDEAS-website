export const ENGAGEMENT_TIME_ZONE = 'America/Vancouver';

export const getEngagementDate = (date: string, time = '12:00') => {
  const [year, month, day] = date.split('-').map(Number);
  const [hours, minutes] = time.split(':').map(Number);
  return new TZDate(year, month - 1, day, hours, minutes, 0, ENGAGEMENT_TIME_ZONE);
};

export const getEngagementDateKey = (date: Date) => {
  const localDate = new TZDate(date, ENGAGEMENT_TIME_ZONE);
  return `${localDate.getFullYear()}-${String(localDate.getMonth() + 1).padStart(2, '0')}-${String(localDate.getDate()).padStart(2, '0')}`;
};

